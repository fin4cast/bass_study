const ENTITIES: Readonly<Record<string, string>> = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

/**
 * Единственное экранирование для разметки, собираемой строкой (innerHTML).
 * Правило: всё, что не является литералом разметки в самом шаблоне, — пользовательские данные,
 * сохранённые значения, имена файлов и устройств, тексты из модели и ошибок — проходит через
 * `escapeHtml`, в том числе внутри атрибутов в двойных кавычках. Без экранирования
 * подставляются только числа, константы этого же модуля и результаты функций,
 * которые сами возвращают разметку (`…Markup`, `render…`) и подчиняются тому же правилу.
 */
export function escapeHtml(value: string | number): string {
  return String(value).replace(/[&<>"']/g, character => ENTITIES[character]!);
}
